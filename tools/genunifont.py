#!/usr/bin/env python3
"""Takes the Arabic glyphs out of GNU Unifont (unifont.hex) for Retro Sans,
retro's UI font: src/retro/unifontar.nim (tools/genretro.py makes the
Arabic outlines from it).

  python3 tools/genunifont.py /usr/share/unifont/unifont.hex

GNU Unifont is (c) Roman Czyborra, Paul Hardy, Qianqian Fang, Andrew Miller,
Johnnie Weaver, David Corbett and others, dual-licensed under the GNU GPL 2+
with the font embedding exception and the SIL Open Font License 1.1; retro
uses it under the SIL OFL 1.1 (see LICENSE).
"""
import sys, os

RANGES = [(0x0600, 0x06FF), (0x0750, 0x077F), (0x08A0, 0x08FF),
          (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]


def main(hexpath):
    glyphs = []
    for line in open(hexpath):
        cp, bits = line.strip().split(':')
        cp = int(cp, 16)
        if any(a <= cp <= b for a, b in RANGES):
            glyphs.append((cp, bits))
    glyphs.sort()
    cps, offs, wide, blob = [], [], [], bytearray()
    for cp, bits in glyphs:
        data = bytes.fromhex(bits)
        cps.append(cp)
        offs.append(len(blob))
        wide.append(1 if len(data) == 32 else 0)
        blob += data
    out = ['## The Arabic glyphs of GNU Unifont (16 pixels high, 8 or 16 wide), for',
           '## Retro Sans, the UI font: its Arabic at one pixel per brick.',
           '## Generated by tools/genunifont.py -- do not edit.',
           '##',
           '## GNU Unifont: (c) Roman Czyborra, Paul Hardy, Qianqian Fang, Andrew',
           '## Miller, Johnnie Weaver, David Corbett and others; used under the SIL',
           '## Open Font License 1.1 (see LICENSE).', '',
           'const',
           '  UniCount* = %d' % len(cps),
           '  uniCps*: array[UniCount, uint16] = [' + ', '.join('%du16' % c if i == 0 else str(c) for i, c in enumerate(cps)) + ']',
           '  uniOffs*: array[UniCount, uint16] = [' + ', '.join('%du16' % o if i == 0 else str(o) for i, o in enumerate(offs)) + ']',
           '  uniWide*: array[UniCount, bool] = [' + ', '.join('true' if w else 'false' for w in wide) + ']',
           '  uniBits* = "' + ''.join('\\x%02x' % b for b in blob) + '"', '']
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'retro', 'unifontar.nim')
    open(path, 'w').write('\n'.join(out))
    print(len(cps), 'glyphs,', len(blob), 'bytes')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/unifont/unifont.hex')
